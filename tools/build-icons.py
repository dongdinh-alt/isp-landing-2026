#!/usr/bin/env python3
"""
Subset the Phosphor Bold icon font to the icons the page actually uses (~150 KB → a few KB).

Scans index.html and assets/js/*.js for `ph-<name>` classes, then:
  - writes assets/fonts/phosphor-bold.woff2 containing only those glyphs
  - rewrites the block between the ICONS markers in assets/css/main.css

Run it again whenever an icon is added or removed:
    python3 tools/build-icons.py [path/to/Phosphor-Bold.woff2] [path/to/style.css]
Without arguments, the two source files are downloaded from unpkg (@phosphor-icons/web@2.1.1).
Needs fontTools + brotli (pip install fonttools brotli).
"""
import io, os, re, sys, urllib.request
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.join(os.path.dirname(__file__), '..')
CDN = 'https://unpkg.com/@phosphor-icons/web@2.1.1/src/bold/'
NON_ICON = {'ph-bold', 'ph-light', 'ph-fill', 'ph-thin', 'ph-duotone'}

def read(src, name):
    if src:
        return open(src, 'rb').read()
    return urllib.request.urlopen(CDN + name).read()

font_bytes = read(sys.argv[1] if len(sys.argv) > 1 else None, 'Phosphor-Bold.woff2')
css_src = read(sys.argv[2] if len(sys.argv) > 2 else None, 'style.css').decode()

used = set()
files = [os.path.join(ROOT, 'index.html')] + [os.path.join(ROOT, 'assets/js', f) for f in os.listdir(os.path.join(ROOT, 'assets/js')) if f.endswith('.js')]
for f in files:
    used |= set(re.findall(r'\bph-[a-z0-9-]+', open(f, encoding='utf-8').read()))
used -= NON_ICON

codes = dict(re.findall(r'\.ph-bold\.(ph-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css_src))
missing = sorted(n for n in used if n not in codes)
if missing:
    sys.exit(f'unknown icons: {missing}')
names = sorted(used)

font = TTFont(io.BytesIO(font_bytes))
opts = subset.Options()
opts.flavor = 'woff2'
opts.layout_features = []
opts.name_IDs = []
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=[int(codes[n], 16) for n in names])
sub.subset(font)
out = os.path.join(ROOT, 'assets/fonts/phosphor-bold.woff2')
font.flavor = 'woff2'
font.save(out)

rules = '\n'.join(f'.ph-bold.{n}:before {{ content: "\\{codes[n]}"; }}' for n in names)
block = f'''/* ICONS:START — generated by tools/build-icons.py ({len(names)} Phosphor Bold icons), do not edit */
@font-face {{ font-family: "Phosphor-Bold"; src: url("../fonts/phosphor-bold.woff2") format("woff2"); font-weight: normal; font-style: normal; font-display: block; }}
.ph-bold {{ font-family: "Phosphor-Bold" !important; speak: never; font-style: normal; font-weight: normal; font-variant: normal; text-transform: none; line-height: 1; letter-spacing: 0; -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale; }}
{rules}
/* ICONS:END */'''

css_path = os.path.join(ROOT, 'assets/css/main.css')
css = open(css_path, encoding='utf-8').read()
if '/* ICONS:START' in css:
    css = re.sub(r'/\* ICONS:START.*?/\* ICONS:END \*/', lambda m: block, css, flags=re.S)
else:
    css = css.replace('\n*, *::before, *::after {', '\n' + block + '\n\n*, *::before, *::after {', 1)
open(css_path, 'w', encoding='utf-8').write(css)
print(f'{len(names)} icons · {os.path.getsize(out)} bytes → assets/fonts/phosphor-bold.woff2')
